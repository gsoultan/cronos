/*
 * Explaining a report, in the portal, against a real cronosd.
 *
 * Driven by scripts/live-explain.sh, which starts cronosd with a stand-in model
 * that records what it is sent. This asserts what a reader sees and what their
 * clicks send: the panel is offered, a summary comes back labelled as
 * generated, a question about one block is sent as that block, and a failure
 * is said in the server's own words.
 */
import { readFileSync } from 'node:fs'
import { chromium } from 'playwright'

const B = process.env.BASE ?? 'http://localhost:5175'
const SENT = process.env.SENT
const SHOT = process.env.SHOT
// Chrome as the other suites use, or a browser named by CHROMIUM where there is none.
const browser = await chromium.launch(process.env.CHROMIUM
  ? { executablePath: process.env.CHROMIUM, args: ['--no-sandbox'] }
  : { channel: 'chrome', args: ['--no-sandbox'] })
const page = await (await browser.newContext({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 2 })).newPage()
let fails = 0
const ok = (name, cond) => { console.log(`  ${cond ? 'ok  ' : 'FAIL'} ${name}`); if (!cond) fails++ }
const errors = []
page.on('pageerror', (e) => errors.push(String(e)))
const bodies = () => readFileSync(SENT, 'utf8').trim().split('\n').filter(Boolean)
  .map((l) => JSON.parse(l).body)
// The newest thing the reader asked, which is the last turn of each request.
const sent = () => bodies().map((b) => b.messages.at(-1).content[0].text)

await page.goto(`${B}/reports/billing-summary`, { waitUntil: 'domcontentloaded' })
await page.locator('[data-testid=live-report]').waitFor({ timeout: 20000 })
await page.locator('[data-testid=explain-button]').waitFor({ timeout: 10000 })
ok('the report offers Explain', await page.locator('[data-testid=explain-button]').isVisible())

await page.click('[data-testid=explain-button]')
await page.locator('[data-testid=explain-panel]').waitFor()
ok('the panel opens', await page.locator('[data-testid=explain-panel]').isVisible())

const before = sent().length
await page.click('[data-testid=explain-ask]')
await page.locator('[data-testid=explain-text]').first().waitFor({ timeout: 15000 })
ok('a summary comes back',
  (await page.locator('[data-testid=explain-text]').first().innerText()).includes('Total billed'))
ok('labelled as generated', await page.locator('text=Generated by AI from the figures shown').first().isVisible())
ok('and the whole report was sent', sent().length === before + 1 && !sent().at(-1).includes('Focus on block'))
ok('the panel is a conversation', (await page.getByText(/^Ask about/).first().isVisible())
  && (await page.getByText('Follow-up question', { exact: true }).isVisible()))

await page.click('[data-testid=explain-about]')
await page.click('[role=option]:has-text("Total billed — figure")')
await page.fill('[data-testid=explain-question]', 'Is this a lot for a month?')
await page.press('[data-testid=explain-question]', 'Enter')
await page.waitForFunction(() => document.querySelectorAll('[data-testid=explain-answer]').length === 2, null, { timeout: 15000 })
const last = sent().at(-1)
ok('Enter asks about the chosen block', last.includes('Focus on block 0 (Total billed)'))
ok('with the question as typed', last.includes('<question>\nIs this a lot for a month?\n</question>'))
ok('and the box is cleared for the next one', (await page.inputValue('[data-testid=explain-question]')) === '')
ok('earlier answers stay', (await page.locator('[data-testid=explain-answer]').count()) === 2)
const second = bodies().at(-1).messages
ok('a follow-up sends the conversation back',
  second.length === 3 && second[1].role === 'assistant' && second[1].content[0].text.includes('What: Total billed'))

await page.click('[data-testid=explain-suggestion]:has-text("How could we improve this?")')
await page.waitForFunction(() => document.querySelectorAll('[data-testid=explain-answer]').length === 3, null, { timeout: 15000 })
ok('advice is offered once a conversation is under way',
  (await page.locator('[data-testid=explain-text]').last().innerText()).includes('Check first:'))
ok('and it builds on both earlier answers', bodies().at(-1).messages.length === 5)
if (SHOT) await page.locator('[data-testid=explain-panel]').screenshot({ path: SHOT })

await page.fill('[data-testid=explain-question]', 'please fail')
await page.click('[data-testid=explain-ask]')
await page.locator('[data-testid=explain-error]').waitFor({ timeout: 15000 })
ok('a provider failure is said plainly',
  (await page.locator('[data-testid=explain-error]').innerText()).includes('No explanation is available right now'))

await page.click('[data-testid=explain-reset]')
ok('a new conversation starts empty', (await page.locator('[data-testid=explain-answer]').count()) === 0)
ok('a failed question stays in the box to try again', (await page.inputValue('[data-testid=explain-question]')) === 'please fail')
await page.fill('[data-testid=explain-question]', '')
await page.click('[data-testid=explain-ask]')
await page.locator('[data-testid=explain-text]').first().waitFor({ timeout: 15000 })
ok('and sends no history', bodies().at(-1).messages.length === 1)

ok('no page errors', errors.length === 0)
if (errors.length) console.log(errors.join('\n'))
await browser.close()
process.exit(fails ? 1 : 0)
